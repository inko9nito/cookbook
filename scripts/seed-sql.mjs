// Writes the migration that seeds the sample recipes (src/demo/data.ts) into the database.
// Run once: node --experimental-strip-types scripts/seed-sql.mjs > netlify/database/migrations/<timestamp>_seed_sample_recipes.sql
import { sampleRecipes } from '../src/demo/data.ts';

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (a) => `ARRAY[${a.map(q).join(', ')}]::text[]`;

const lines = [
  '-- Sample recipes, so the app has something to show before the real recipes are imported (Phase 3).',
  '-- Generated by scripts/seed-sql.mjs from src/demo/data.ts. Delete them in the app whenever.',
];
for (const r of sampleRecipes) {
  lines.push(
    `INSERT INTO recipes (id, title, source, servings, serving_size, prep_minutes, cook_minutes, total_minutes, photos, tags, ingredients, steps, notes, rating, times_made, created_at, updated_at) VALUES (` +
      [
        q(r.id), q(r.title), q(r.source), r.servings, q(r.servingSize), r.prepMinutes, r.cookMinutes, r.minutes,
        j(r.photos), arr(r.tags), j(r.ingredients.map((i) => (i.kind === 'header' ? i : { ...i, raw: [i.amount, i.unit, i.name].filter(Boolean).join(' ') + (i.note ? `, ${i.note}` : '') }))),
        j(r.steps), q(r.notes), r.rating, r.timesMade, q(r.createdAt), q(r.createdAt),
      ].join(', ') +
      `) ON CONFLICT (id) DO NOTHING;`,
  );
}
console.log(lines.join('\n'));
